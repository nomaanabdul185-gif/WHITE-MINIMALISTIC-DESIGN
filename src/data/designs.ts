export function calculateMatchScore(design: DesignItem, brief: BriefSelection): { score: number; maxScore: number; percentage: number; matchedFields: string[] } {
  const fields: (keyof BriefSelection)[] = ['property', 'project', 'homeType', 'budget', 'designChoice', 'style'];
  const matchedFields: string[] = [];
  
  fields.forEach(field => {
    if (design[field] === brief[field]) {
      matchedFields.push(field);
    }
  });

  const score = matchedFields.length;
  const maxScore = fields.length;
  const percentage = Math.round((score / maxScore) * 100);

  return { score, maxScore, percentage, matchedFields };
}
